int min(double arr[], int length) {
  int best = 0;
  for (int i = 0; i < length; i++) {
    if (arr[i] < arr[best]) {
      best = i;
    }
  }
  return best;
}

int max(double arr[], int length) {
  int best = 0;
  for (int i = 0; i < length; i++) {
    if (arr[i] > arr[best]) {
      best = i;
    }
  }
  return best;
}


int find_saddles(double A[N][N]) {
  int maximums[N];
  int minimums[N];
  for (int i = 0; i < N; i++) {
    int row_min = min(A[i], N);
    int row_max = max(A[i], N);
    maximums[i] = row_max;
    minimums[i] = row_min;
  }
  return 0;
}

